-- Instalacion NUEVA en un esquema VACIO, conectado como ELTRUJILLANO.
-- Incluye el resultado de las migraciones V1, V2 y V3: NO aplicarlas despues.
-- IDs 1..999 reservados para datos iniciales. Los IDs de la aplicacion empiezan en 1000.
-- Oracle 19c/21c/23ai/Free. No contiene DROP ni modifica esquemas existentes.
DECLARE
    v_tablas NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','SESSION_USER') IN ('SYS','SYSTEM')
       OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> SYS_CONTEXT('USERENV','SESSION_USER') THEN
        RAISE_APPLICATION_ERROR(-20002, 'Conectese con el usuario propietario de la aplicacion.');
    END IF;
    SELECT COUNT(*) INTO v_tablas FROM USER_TABLES;
    IF v_tablas > 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'El esquema debe estar vacio. Use migraciones si ya tiene tablas.');
    END IF;
END;
/

