-- Para bases YA creadas: tabla de enlaces para restablecer la contraseña (recuperación por correo).
-- En una instalación nueva no hace falta: 01_tablas.sql ya la incluye.
-- Ejecutar UNA sola vez con el usuario dueño del esquema.
-- Se guarda solo el hash SHA-256 del enlace (nunca el enlace en claro); cada enlace vence y se usa una sola vez.
CREATE TABLE PASSWORD_RESET_TOKEN (
    ID_TOKEN NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    ID_USUARIO NUMBER(19,0) NOT NULL,
    TOKEN_HASH VARCHAR2(64 CHAR) NOT NULL,
    FECHA_CREACION TIMESTAMP(6) NOT NULL,
    FECHA_EXPIRACION TIMESTAMP(6) NOT NULL,
    USADO NUMBER(1,0) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_PRT_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT UK_PRT_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT CK_PRT_USADO CHECK (USADO IN (0,1))
);
CREATE INDEX IX_PRT_USUARIO ON PASSWORD_RESET_TOKEN(ID_USUARIO, FECHA_CREACION);
