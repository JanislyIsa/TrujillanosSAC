-- Consultas de diagnostico, sin modificar datos. Ejecutar como ELTRUJILLANO.
SELECT SYS_CONTEXT('USERENV','SESSION_USER') AS USUARIO,
       SYS_CONTEXT('USERENV','CON_NAME') AS PDB FROM DUAL;
SELECT COUNT(*) AS TABLAS_CREADAS FROM USER_TABLES;
SELECT TABLE_NAME FROM USER_TABLES ORDER BY TABLE_NAME;
SELECT CONSTRAINT_NAME, TABLE_NAME, STATUS, VALIDATED
FROM USER_CONSTRAINTS WHERE STATUS <> 'ENABLED' OR VALIDATED <> 'VALIDATED';
SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS <> 'VALID';

SELECT U.USERNAME, R.NOMBRE AS ROL, C.NOMBRE AS CARGO
FROM USUARIO U JOIN USUARIO_ROL UR ON UR.ID_USUARIO=U.ID_USUARIO
JOIN ROL R ON R.ID_ROL=UR.ID_ROL
LEFT JOIN EMPLEADOS E ON E.ID_PERSONA=U.ID_PERSONA
LEFT JOIN CARGO C ON C.ID_CARGO=E.CARGO ORDER BY U.ID_USUARIO;

SELECT 'PRODUCTO' AS TIPO, NOMBRE, STOCK, STOCK_MINIMO, STOCK_LIMITE,
       CASE WHEN STOCK < STOCK_MINIMO THEN 'BAJO' WHEN STOCK > STOCK_LIMITE THEN 'SOBRESTOCK' ELSE 'NORMAL' END AS ESTADO
FROM PRODUCTO
UNION ALL
SELECT 'INSUMO', NOMBRE, STOCK, STOCK_MINIMO, STOCK_LIMITE,
       CASE WHEN STOCK < STOCK_MINIMO THEN 'BAJO' WHEN STOCK > STOCK_LIMITE THEN 'SOBRESTOCK' ELSE 'NORMAL' END
FROM INSUMO;

-- Debe devolver cero filas: todos los movimientos tienen comprobante persistido.
SELECT M.ID_MOVIMIENTO AS SIN_COMPROBANTE FROM MOVIMIENTO M
LEFT JOIN COMPROBANTE_MOVIMIENTO C ON C.ID_MOVIMIENTO=M.ID_MOVIMIENTO
WHERE C.ID_MOVIMIENTO IS NULL;
-- Debe devolver cero filas: las cantidades y saldos de cada detalle concuerdan.
SELECT M.ID_MOVIMIENTO AS SALDO_INCONSISTENTE FROM MOVIMIENTO M
JOIN (SELECT ID_MOVIMIENTO, CANTIDAD, STOCK_ANTERIOR, STOCK_NUEVO FROM DETALLE_MOV_PRODUCTO
      UNION ALL SELECT ID_MOVIMIENTO, CANTIDAD, STOCK_ANTERIOR, STOCK_NUEVO FROM DETALLE_MOV_INSUMO) D
ON D.ID_MOVIMIENTO=M.ID_MOVIMIENTO
WHERE D.STOCK_NUEVO <> D.STOCK_ANTERIOR + CASE WHEN M.TIPO_MOVIMIENTO='Ingreso' THEN D.CANTIDAD ELSE -D.CANTIDAD END;
SELECT S.ID_SOLICITUD, E.NOMBRE AS ESTADO, P.NOMBRE AS PROVEEDOR, COUNT(D.ID_DETALLE_SOL) AS LINEAS
FROM SOLICITUD_COMPRA S JOIN ESTADO_SOLICITUD E ON E.ID_ESTADO=S.ID_ESTADO
JOIN PERSONA P ON P.ID_PERSONA=S.ID_PROVEEDOR
LEFT JOIN DETALLE_SOLICITUD D ON D.ID_SOLICITUD=S.ID_SOLICITUD
GROUP BY S.ID_SOLICITUD,E.NOMBRE,P.NOMBRE;
SELECT ID_DESTINATARIO, COUNT(*) AS NOTIFICACIONES FROM NOTIFICACION_INVENTARIO GROUP BY ID_DESTINATARIO;
