-- Aplicar una sola vez en el esquema Oracle de desarrollo antes de iniciar esta versión.
-- Registra operaciones críticas ya confirmadas, asociadas al usuario y al X-Request-Id.
CREATE TABLE AUDITORIA_EVENTOS (
    ID_EVENTO NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    FECHA TIMESTAMP(6) NOT NULL,
    USUARIO VARCHAR2(50 CHAR) NOT NULL,
    ACCION VARCHAR2(40 CHAR) NOT NULL,
    ENTIDAD VARCHAR2(40 CHAR) NOT NULL,
    ENTIDAD_ID NUMBER(19,0),
    DETALLE VARCHAR2(500 CHAR),
    REQUEST_ID VARCHAR2(36 CHAR),
    CONSTRAINT PK_AUDITORIA_EVENTOS PRIMARY KEY (ID_EVENTO)
);
CREATE INDEX IX_AUDITORIA_FECHA ON AUDITORIA_EVENTOS (FECHA, ID_EVENTO);
CREATE INDEX IX_AUDITORIA_USUARIO_FECHA ON AUDITORIA_EVENTOS (USUARIO, FECHA);
COMMIT;
