-- Compras e Inventario manejan las cantidades de insumos como unidades enteras.
-- Esta migracion se detiene sin modificar datos si existen cantidades fraccionarias
-- o superiores al rango Integer soportado por el backend.
DECLARE
    v_invalidas NUMBER;
BEGIN
    SELECT
        (SELECT COUNT(*) FROM DETALLE_SOLICITUD
         WHERE CANTIDAD <> TRUNC(CANTIDAD) OR CANTIDAD < 1 OR CANTIDAD > 2147483647)
      + (SELECT COUNT(*) FROM DETALLE_COTIZACION
         WHERE CANTIDAD <> TRUNC(CANTIDAD) OR CANTIDAD < 1 OR CANTIDAD > 2147483647)
      + (SELECT COUNT(*) FROM DETALLE_ORDEN_COMPRA
         WHERE CANTIDAD <> TRUNC(CANTIDAD) OR CANTIDAD < 1 OR CANTIDAD > 2147483647)
      INTO v_invalidas
      FROM DUAL;

    IF v_invalidas > 0 THEN
        RAISE_APPLICATION_ERROR(-20004,
            'V4 abortada: hay cantidades fraccionarias o fuera del rango Integer. Corrija los datos antes de reintentar.');
    END IF;
END;
/

ALTER TABLE DETALLE_SOLICITUD MODIFY (CANTIDAD NUMBER(10,0) NOT NULL);
ALTER TABLE DETALLE_COTIZACION MODIFY (CANTIDAD NUMBER(10,0) NOT NULL);
ALTER TABLE DETALLE_ORDEN_COMPRA MODIFY (CANTIDAD NUMBER(10,0) NOT NULL);

ALTER TABLE DETALLE_SOLICITUD ADD CONSTRAINT CK_DS_CANT_INT
    CHECK (CANTIDAD BETWEEN 1 AND 2147483647);
ALTER TABLE DETALLE_COTIZACION ADD CONSTRAINT CK_DC_CANT_INT
    CHECK (CANTIDAD BETWEEN 1 AND 2147483647);
ALTER TABLE DETALLE_ORDEN_COMPRA ADD CONSTRAINT CK_DOC_CANT_INT
    CHECK (CANTIDAD BETWEEN 1 AND 2147483647);
