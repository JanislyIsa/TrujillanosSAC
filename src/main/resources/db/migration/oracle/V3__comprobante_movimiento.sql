CREATE TABLE COMPROBANTE_MOVIMIENTO (
    ID_MOVIMIENTO NUMBER(19,0) PRIMARY KEY,
    CODIGO VARCHAR2(30 CHAR) NOT NULL,
    FECHA_EMISION TIMESTAMP(6) NOT NULL,
    RESPONSABLE VARCHAR2(100 CHAR),
    MOTIVO VARCHAR2(200 CHAR),
    CONSTRAINT FK_CM_MOVIMIENTO FOREIGN KEY (ID_MOVIMIENTO) REFERENCES MOVIMIENTO(ID_MOVIMIENTO),
    CONSTRAINT UK_CM_CODIGO UNIQUE (CODIGO)
);

-- Conserva los codigos anteriores. No inventa saldos historicos ausentes.
INSERT INTO COMPROBANTE_MOVIMIENTO (ID_MOVIMIENTO, CODIGO, FECHA_EMISION, RESPONSABLE, MOTIVO)
SELECT ID_MOVIMIENTO,
       'CM-' || CASE WHEN ID_MOVIMIENTO < 1000
                    THEN LPAD(TO_CHAR(ID_MOVIMIENTO, 'FM9999999999999999999'), 3, '0')
                    ELSE TO_CHAR(ID_MOVIMIENTO, 'FM9999999999999999999') END,
       HORA, RESPONSABLE, MOTIVO
FROM MOVIMIENTO;
COMMIT;
